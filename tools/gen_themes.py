#!/usr/bin/env python3
"""Builds src/themes/*.css from Discord's own web client stylesheets.

Usage: gen_themes.py DIR_WITH_DISCORD_CSS
Reads every .css file in the directory, picks the variables that
`.theme-dark|darker|midnight|light` define, resolves them to colours, and
writes one @define-color palette per theme.
"""
import colorsys, glob, re, sys

src, out = sys.argv[1], 'src/themes'
root, themes = {}, {t: {} for t in ('dark', 'darker', 'midnight', 'light')}
VAR = re.compile(r'(--[a-z0-9-]+)\s*:\s*([^;]+)')
for path in glob.glob(f'{src}/*.css'):
    text = open(path, errors='ignore').read()
    for sel, body in re.findall(r'([^{}]*)\{([^{}]*)\}', text):
        names = [s.strip() for s in sel.split(',')]
        for k, v in VAR.findall(body):
            if ':root' in names or any(n.endswith(':root') for n in names):
                root.setdefault(k, v.strip())
            for t in themes:
                if f'.theme-{t}' in names:
                    themes[t][k] = v.strip()

def hexa(h, s, l, a=None):
    r, g, b = colorsys.hls_to_rgb(h / 360, l / 100, s / 100)
    x = '#%02x%02x%02x' % (round(r * 255), round(g * 255), round(b * 255))
    return x if a is None or a >= 0.999 else x + '%02x' % round(a * 255)

def norm(v):
    return re.sub(r'calc\(var\(--saturation-factor,\s*1\)\*([\d.]+)%\)', r'\1%', v.strip())

def resolve(v, table, depth=0):
    if depth > 14:
        return None
    v = norm(v)
    m = re.fullmatch(r'var\((--[a-z0-9-]+)(?:,.*)?\)', v)
    if m:
        return resolve(table.get(m.group(1), ''), table, depth + 1)
    m = re.match(r'color-mix\(in oklab,(.*?) 100%,', v)
    if m:
        return resolve(m.group(1), table, depth + 1)
    m = re.fullmatch(r'hsl\(\s*var\((--[a-z0-9-]+)\)\s*/\s*([\d.]+)\)', v)
    if m:
        p = re.findall(r'[\d.]+', norm(table.get(m.group(1), '')))
        if len(p) >= 3:
            return hexa(float(p[0]), float(p[1]), float(p[2]), float(m.group(2)))
    return v if v.startswith('#') else None

# GTK colour name -> Discord token
MAP = {
    'bg_lowest': 'background-base-lowest',      # server list
    'bg_lower': 'background-base-lower',        # channel list, user panel
    'bg_low': 'background-base-low',
    'bg_chat': 'chat-background-default',       # message area
    'bg_surface': 'background-surface-high',
    'bg_surface_higher': 'background-surface-higher',
    'bg_surface_highest': 'background-surface-highest',
    'bg_input': 'channeltextarea-background',
    'text_default': 'text-default',
    'text_strong': 'text-strong',
    'text_muted': 'text-muted',
    'text_subtle': 'text-subtle',
    'channel_default': 'channels-default',
    'interactive_hover': 'interactive-background-hover',
    'interactive_active': 'interactive-background-active',
    'interactive_text': 'interactive-text-default',
    'interactive_text_hover': 'interactive-text-hover',
    'border_subtle': 'border-subtle',
    'border_normal': 'border-normal',
    'link': 'text-link',
    'mention_bg': 'mention-background',
    'mention_fg': 'mention-foreground',
    'brand': 'background-brand',
    'positive': 'status-positive',
    'danger': 'status-danger',
    'warning': 'status-warning',
    'scrollbar': 'scrollbar-thin-thumb',
}
for name, vars_ in themes.items():
    table = {**root, **vars_}
    lines = [f'/* Generated by tools/gen_themes.py from Discord\'s .theme-{name}. */']
    for gtk, token in MAP.items():
        value = resolve(table.get('--' + token, ''), table)
        if value is None:
            sys.exit(f'{name}: cannot resolve {token}')
        lines.append(f'@define-color {gtk} {value};')
    open(f'{out}/{name}.css', 'w').write('\n'.join(lines) + '\n')
    print(name, len(MAP), 'colours')
