#!/usr/bin/env python3
"""Builds src/icons/*.svg and src/icon_data.rs from Material Design Icons.

Usage: gen_icons.py

Downloads each icon from the Pictogrammers MaterialDesign-SVG repository
(Apache License 2.0, https://github.com/Templarian/MaterialDesign-SVG) and
rewrites its colour to the GTK symbolic foreground (#bebebe) so themes can
recolour it. Run it from the project root.
"""
import os, re, sys, urllib.request

BASE = 'https://raw.githubusercontent.com/Templarian/MaterialDesign-SVG/master/svg/'

# our icon name -> Material Design Icons name
ICONS = {
    'announcements': 'bullhorn', 'arrow-angle-left-up': 'arrow-top-left', 'at': 'at',
    'attachment': 'paperclip', 'bell-slash': 'bell-off', 'bell': 'bell', 'checkmark-small': 'check',
    'chevron-small-down': 'chevron-down', 'chevron-small-right': 'chevron-right',
    'circle-plus': 'plus-circle', 'clock': 'clock-outline', 'copy': 'content-copy', 'crown': 'crown',
    'emoji-slightly-smiling-face': 'emoticon-happy-outline', 'eye': 'eye', 'flag': 'flag',
    'folder': 'folder', 'forum': 'forum', 'gif': 'file-gif-box', 'gift': 'gift', 'group': 'account-group',
    'hashmark': 'pound', 'headphones-slash': 'headphones-off', 'headphones': 'headphones',
    'image': 'image', 'link': 'link-variant', 'lock': 'lock', 'magnifying-glass': 'magnify',
    'menu': 'menu', 'microphone-slash': 'microphone-off', 'microphone': 'microphone',
    'more-horizontal': 'dots-horizontal', 'pencil': 'pencil', 'phone-call': 'phone',
    'phone-hang-up': 'phone-hangup', 'pin': 'pin', 'plus-large': 'plus', 'screen': 'monitor',
    'settings': 'cog', 'stage': 'podcast', 'sticker': 'sticker-emoji', 'thread': 'comment-text-multiple',
    'trash': 'delete', 'video': 'video', 'voice-low': 'volume-low', 'voice-normal': 'volume-high',
    'x-small': 'close',
}

os.makedirs('src/icons', exist_ok=True)
for old in os.listdir('src/icons'):
    os.remove(os.path.join('src/icons', old))

written, failed = [], []
for ours, mdi in ICONS.items():
    try:
        svg = urllib.request.urlopen(BASE + mdi + '.svg', timeout=30).read().decode()
    except Exception as e:
        failed.append(f'{ours} ({mdi}): {e}')
        continue
    paths = re.findall(r'<path d="([^"]+)"', svg)
    if not paths:
        failed.append(f'{ours} ({mdi}): no path')
        continue
    name = f'icon-{ours}-symbolic'
    with open(f'src/icons/{name}.svg', 'w') as f:
        f.write('<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24">'
                + ''.join(f'<path fill="#bebebe" d="{d}"/>' for d in paths) + '</svg>')
    written.append(name)

with open('src/icon_data.rs', 'w') as f:
    f.write('// Generated by tools/gen_icons.py from Material Design Icons (Apache-2.0). Do not edit.\n\n')
    f.write('/// (icon name, SVG source) for every icon.\n')
    f.write('pub const ICONS: &[(&str, &str)] = &[\n')
    for name in written:
        f.write(f'    ("{name}", include_str!("icons/{name}.svg")),\n')
    f.write('];\n')
print(len(written), 'icons written')
if failed:
    print('FAILED:\n  ' + '\n  '.join(failed))
    sys.exit(1)
